import type { ThemeKey } from './themes';

/* ══════════ 문항 묶음 ══════════
   제도는 자주 바뀐다. 문항을 앱에 박아 두면 최저임금 하나 고치는 데 스토어 심사를 다시 받는다.
   그래서 이 파일은 "내장 폴백"일 뿐이고, 실제 갱신은 EAS Update로 같은 모양의 JSON을 내려받아
   덮어쓴다(core/pack-loader.ts). 문항마다 확인처와 기준일이 붙는다. */

export interface Question {
  q: string;
  a: string[];
  /** 정답 인덱스 */
  ok: number;
  why: string;
}

export interface Fit {
  status?: string[];
  ageMax?: number;
  regions?: string[];
}

export interface Quest {
  id: string;
  theme: ThemeKey;
  title: string;
  xp: number;
  coin: number;
  fit: Fit;
  npc: string;
  reward: string | null;
  intro: string;
  qs: Question[];
  stat: Partial<Record<ThemeKey, number>>;
  /** [확인처 이름, 링크] */
  src: [string, string];
}

export interface Boss {
  id: string;
  name: string;
  /** 세울 손그림 (sprite/cast.ts의 NpcId) */
  face: string;
  /** 도전 조건이 걸린 스탯과 값 */
  stat: 'ju' | 'sik' | 'ui' | 'geum' | 'jik';
  need: number;
  hp: number;
  atk: number;
  intro: string;
  win: string;
  lose: string;
  src: [string, string];
  qs: Question[];
}

export interface Pack {
  ver: string;
  asOf: string;
  quests: Quest[];
  bosses: Boss[];
}

