/* ══════════ 3. 트는 함수 ══════════ */
function lifeMidAgeKo(n) {
  var T = { 2: '스물', 3: '서른', 4: '마흔', 5: '쉰', 6: '예순' }, O = ['', '하나', '둘', '셋', '넷', '다섯', '여섯', '일곱', '여덟', '아홉'];
  return (T[Math.floor(n / 10)] || '') + O[n % 10];
}
var LIFE_MID_FLAGS = ['solo', 'own', 'tight', 'p_hs', 'p_jc'];
function lifeMidFlags() {
  var L = (typeof S !== 'undefined' && S && S.life) || {}, p = L.prof || {};
  var m = (typeof lifePickV === 'function') ? lifePickV('marry') : null;
  var own = !!(typeof TIERS !== 'undefined' && S && TIERS[S.tier] && TIERS[S.tier].own);
  return { solo: m === 'solo', own: own, tight: p.income === '빠듯', p_hs: p.path === '고졸', p_jc: p.path === '전문대' };
}
function lifeMidNeedOk(need, fl) {
  if (!need) return true;
  for (var k in need) if (!!fl[k] !== !!need[k]) return false;
  return true;
}
/* 장면 목록에 갈래 patch를 입힌다. 원본은 건드리지 않는다 */
function lifeMidBuild(list, patch, fl) {
  var out = JSON.parse(JSON.stringify(list || [])), adds = {};
  LIFE_MID_FLAGS.forEach(function (f) {
    if (!fl[f] || !patch || !patch[f]) return;
    for (var i in patch[f]) {
      var v = patch[f][i];
      if (v === null) { out[i] = null; continue; }
      if (v._after) adds[i] = (adds[i] || []).concat(JSON.parse(JSON.stringify(v._after)));
      for (var k in v) if (k !== '_after') out[i][k] = JSON.parse(JSON.stringify(v[k]));
    }
  });
  var res = [];
  out.forEach(function (p, i) { if (p) res.push(p); if (adds[i]) res = res.concat(adds[i]); });
  if (fl.solo) res.forEach(function (p) {
    if (!p.cast) return;
    p.cast = p.cast.filter(function (c) { return c[0] !== 'partner'; });
    if (p.cast.length === 1) p.cast[0] = [p.cast[0][0], 'C'];
  });
  return res;
}
/* 그 나이 자리의 세월 다리 열쇠와 사건 id */
function lifeMidSlot(age, fl) {
  fl = fl || lifeMidFlags();
  var s = LIFE_MID_SLOTS.filter(function (x) { return x.age === age; })[0]; if (!s) return null;
  var y = s.y.filter(function (k) { return lifeMidNeedOk(LIFE_MID_YEARS[k].need, fl); })[0] || null;
  var e = s.ev.filter(function (k) { return lifeMidNeedOk(LIFE_MID[k].need, fl); })[0] || null;
  return { y: y, ev: e };
}
/* 세월 다리(있으면) + 사건 장면. age를 주면 그 나이로 {ageKo}를 채운다 */
function lifeMidScenes(id, fl, age, withYears) {
  fl = fl || lifeMidFlags();
  var ev = LIFE_MID[id], sc = [];
  if (!ev) return [];
  age = age || ev.age;
  if (withYears !== false && ev.y && LIFE_MID_YEARS[ev.y]) sc = lifeMidBuild(LIFE_MID_YEARS[ev.y].scenes, LIFE_MID_YEARS[ev.y].patch, fl);
  sc = sc.concat(lifeMidBuild(ev.scenes, ev.patch, fl));
  return lifeMidFill(sc, age);
}
/* {ageKo}와 lifeFillVals 칸을 채운다. lifeFill이 없으면(검사용) {ageKo}만 */
function lifeMidFill(sc, age) {
  var f = (typeof lifeFillVals === 'function') ? lifeFillVals() : {};
  f.ageKo = lifeMidAgeKo(age);
  if (typeof lifeFill === 'function') return lifeFill(sc, f);
  return sc.map(function (p) { p.text = p.text.map(function (t) { return String(t).replace(/\{ageKo\}/g, f.ageKo); }); return p; });
}
/* 세월 다리만(사건이 없는 자리, 예: y22) */
function lifeMidYearScenes(ykey, fl, age) {
  fl = fl || lifeMidFlags();
  var y = LIFE_MID_YEARS[ykey]; if (!y) return [];
  return lifeMidFill(lifeMidBuild(y.scenes, y.patch, fl), age || y.age);
}
/* 끝 장면 + 보상 카드. 처음이거나 더 잘했을 때만 차액을 준다(rentEnd와 같은 방식). 기록은 S.life.mid[id] */
function lifeMidEnd(id, ok, n) {
  var ev = LIFE_MID[id], g = ok >= n ? 'good' : ok >= n - 1 ? 'ok' : 'bad', R = LIFE_MID_REW, rank = { good: 0, ok: 1, bad: 2 };
  var L = S.life, was = (L.mid = L.mid || {})[id], rows = [[ev.ends[g][0] + ' ' + (ev.ends[g][1] || ''), '']];
  if (was == null || rank[g] < rank[was]) {
    var p = was == null ? { xp: 0, coin: 0, st: 0 } : R[was], e = R[g];
    var gx = Math.max(0, e.xp - p.xp), gc = Math.max(0, e.coin - p.coin), gs = Math.max(0, e.st - p.st);
    L.mid[id] = g; S.xp += gx; S.coin += gc; S.stats[ev.stat] = Math.min(100, (S.stats[ev.stat] || 0) + gs);
    while (S.xp >= need(S.lv)) { S.xp -= need(S.lv); S.lv++; }
    rows.push(['보상', '+' + gx + ' XP · ￦' + gc]);
    if (typeof THEMES !== 'undefined' && THEMES[ev.stat]) rows.push([THEMES[ev.stat].full + ' 스탯', '+' + gs]);
  }
  rows.push(['확인처 · ' + ev.src.map(function (s) { return s[0].split(' · ')[0]; }).filter(function (v, i, a) { return a.indexOf(v) === i; }).slice(0, 3).join(' · '), '', '#9B93A8']);
  save();
  return [{ bg: 'night', cast: [['hero', 'C']], text: ev.ends[g] },
          { type: 'reward', head: 'LIFE EVENT', grade: g, card: ['', ev.title + ' · ' + ev.sub], rows: rows }];
}
